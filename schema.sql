-- 1. Buat Tabel Admins
CREATE TABLE IF NOT EXISTS public.admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) UNIQUE NOT NULL,
    password VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    role VARCHAR(50) DEFAULT 'operator',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Buat Tabel Scan Logs (Audit Log Lapangan)
CREATE TABLE IF NOT EXISTS public.scan_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_code VARCHAR(50) NOT NULL,
    participant_name VARCHAR(255),
    gate_name VARCHAR(100) NOT NULL,
    scan_status VARCHAR(50) NOT NULL, -- 'VALID', 'ALREADY_ATTENDED', 'INVALID'
    response_message TEXT,
    scanned_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Buat Tabel Certificates (Penerbitan E-Sertifikat)
CREATE TABLE IF NOT EXISTS public.certificates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_code VARCHAR(50) UNIQUE NOT NULL,
    certificate_no VARCHAR(100) UNIQUE NOT NULL,
    participant_name VARCHAR(255) NOT NULL,
    event_title VARCHAR(255) NOT NULL,
    issued_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Insert Default Admin
INSERT INTO public.admins (username, password, full_name, role)
VALUES ('admin', 'admin123', 'Administrator Utama', 'superadmin')
ON CONFLICT (username) DO NOTHING;

-- 5. Aktifkan RLS dan izinkan akses via Service Role
ALTER TABLE public.admins ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.scan_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.certificates ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow all operations for service role on admins" ON public.admins
    FOR ALL USING (true) WITH CHECK (true);

CREATE POLICY "Allow all operations for service role on scan_logs" ON public.scan_logs
    FOR ALL USING (true) WITH CHECK (true);

CREATE POLICY "Allow all operations for service role on certificates" ON public.certificates
    FOR ALL USING (true) WITH CHECK (true);
